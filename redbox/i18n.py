def detect_windows_lang():
    try:
        lid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        return "ko" if (lid & 0x3FF) == 0x12 else "en"
    except Exception:
        return "en"


def set_language(setting):
    global _lang
    _lang = detect_windows_lang() if setting in (None, "", "auto") else ("ko" if setting == "ko" else "en")
    return _lang


def lang():
    return _lang


def tr(key):
    v = T.get(key)
    if not v:
        return key
